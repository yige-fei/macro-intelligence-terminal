"use client";

// Read-only Settings & About page. It shows what this build contains and what it does not; it stores and
// changes nothing (no preferences, no storage writes). The Market workspace's saved layout stays in its own store
// and is reset from Market → Reset layout, as before.

import { useQuery } from "@tanstack/react-query";
import ShellHeader from "./ShellHeader";
import { SoftwareLicences } from "./widgets/SourcesWidget";
import { dataIncluded, HISTORICAL_DATA } from "../lib/api";
import { BUILD, PRODUCT_NAME } from "../lib/buildInfo";
import { fmtUtcShort, loadR2Manifest, loadReleaseDesk } from "../lib/releaseDesk";

function Section({ title, children, id }: { title: string; children: React.ReactNode; id: string }) {
  return (
    <section className="terminal-panel !h-auto" aria-label={title} data-testid={`settings-${id}`}>
      <div className="panel-title !cursor-default"><span>{title}</span></div>
      <div className="p-3 text-[12px] flex flex-col gap-2">{children}</div>
    </section>
  );
}

export default function SettingsView() {
  const { data: load } = useQuery({ queryKey: ["release-desk"], queryFn: loadReleaseDesk, staleTime: Infinity, retry: false });
  const { data: r2 } = useQuery({ queryKey: ["release-desk-r2-manifest"], queryFn: loadR2Manifest, staleTime: Infinity, retry: false });
  const desk = load?.kind === "ok" ? load.data : null;
  const excluded = HISTORICAL_DATA === "excluded";
  const st = (f: Parameters<typeof dataIncluded>[0], kind: string) => (dataIncluded(f) ? `INCLUDED · ${kind}` : "NOT INCLUDED");
  const rows: Array<{ what: string; source: string; status: string; note: string; id: string }> = [
    {
      id: "desk", what: "Release desk (Macro → Release schedule)", source: "U.S. Bureau of Labor Statistics; U.S. Bureau of Economic Analysis (official pages)",
      status: desk ? "INCLUDED" : "NOT AVAILABLE",
      note: desk
        ? `${desk.events.length} events · schedule and publication status only, no economic values · data as of ${fmtUtcShort(desk.as_of_utc)}${r2 ? ` · export ${r2.export.sha256.slice(0, 12)} · dataset ${r2.dataset.tree_sha256.slice(0, 12)}` : ""}`
        : "The release-desk export could not be read.",
    },
    { id: "prices", what: "Market charts: DEMO-A, DEMO-B, DEMO-C, DEMO-D daily bars", source: "Generated by this repository (terminal_demo.generate, seeded)",
      status: st("etf_prices.json", "SIMULATED"), note: "Simulated values, not real market prices." },
    { id: "overlay", what: "Event-overlay chart data: DEMO-A to DEMO-D, 2025-01-02 to 2026-10-16", source: "Generated by this repository (separate seed)",
      status: st("event_overlay_prices.json", "SIMULATED"),
      note: "Simulated values ending at the release-desk snapshot (2026-10-17). Markers show the dates of real releases; the bars simulate no reaction to them." },
    { id: "imported", what: "Your own daily OHLCV file (Market → IMPORT LOCAL DATA)", source: "A .csv or .json file you choose",
      status: "OPTIONAL · LOCAL ONLY",
      note: "Read in this browser tab only: not uploaded, not saved, gone after a reload. Checked for structure and numbers only; its source, accuracy and your right to use it are not verified." },
    { id: "macro", what: "Point-in-time macro series (Market → PIT macro)", source: "None bundled", status: st("macro_series.json", ""),
      note: "No lawfully redistributable point-in-time macro dataset is included yet; official direct-source adapters are planned." },
    { id: "research", what: "Research figures (Research)", source: "Generated by this repository (random draws)", status: st("research.json", "ILLUSTRATIVE"),
      note: "Illustrative only: no model was fitted and nothing was evaluated. The author's private historical evaluation is not included." },
  ];
  return (
    <div className="flex flex-col h-screen">
      <ShellHeader current="settings" badge="SETTINGS & ABOUT · READ-ONLY" />
      <main className="flex-1 overflow-auto">
        <div className="max-w-[1100px] mx-auto px-4 py-4 flex flex-col gap-3" data-testid="settings-view">
          <Section title="About" id="about">
            <p><b className="amber">{PRODUCT_NAME}</b> — local portfolio demo, served on this computer only (loopback). Not live, and nothing
              here is a trading signal or a prediction.</p>
            {/* T4-AFK: two-column metadata — every value starts at the same position (data-table cells default to right-aligned). */}
            <table className="data-table" data-testid="settings-about-meta"><tbody>
              <tr className="align-top"><td className="w-[150px]">Frontend build</td><td className="!text-left !whitespace-normal break-all" data-testid="settings-build-id">{BUILD.sourceSha256 || "unavailable"}</td></tr>
              <tr className="align-top"><td className="w-[150px]">Built (UTC)</td><td className="!text-left !whitespace-normal" data-testid="settings-build-time">{BUILD.builtUtc || "unavailable"}</td></tr>
              <tr className="align-top"><td className="w-[150px]">Data mode</td><td className="!text-left !whitespace-normal" data-testid="settings-data-mode">{excluded ? "Metadata only — market and research data not included" : "Demo — simulated market bars and illustrative research figures; official release metadata"}</td></tr>
            </tbody></table>
            <p className="dim">The build id is the SHA-256 of this build&apos;s source file list; it identifies the code, not the data.</p>
          </Section>

          <Section title="Data in this build" id="data">
            <table className="data-table"><thead><tr><th className="!text-left">Data</th><th className="!text-left">Source</th><th className="!text-left">Status</th><th className="!text-left">Note</th></tr></thead>
              <tbody>
                {rows.map((r) => (
                  <tr key={r.id} data-testid={`data-row-${r.id}`} className="align-top">
                    <td className="!text-left !whitespace-normal">{r.what}</td>
                    <td className="!text-left !whitespace-normal">{r.source}</td>
                    <td className={`!text-left ${r.status.startsWith("INCLUDED") ? "text-[var(--up)]" : "amber"}`}>{r.status}</td>
                    <td className="!text-left !whitespace-normal dim">{r.note}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            <p className="dim">Real and simulated data are never mixed in one dataset. Nothing on this page fetches or changes data.</p>
          </Section>

          <Section title="Research status" id="research">
            <p>The Research page demonstrates how a macro-versus-market evaluation is presented. In this repository its figures are
              <b> illustrative random draws</b>, not results; no model is fitted or evaluated here.</p>
            <p className="dim">The author&apos;s private historical evaluation, and the data it used, are not part of this repository. Nothing here
              establishes a forecasting edge, and nothing here is a backtest or a trading signal. See docs/RESEARCH.md.</p>
          </Section>

          <Section title="Implemented and planned" id="capabilities">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
              <div>
                <b>In this build</b>
                <ul className="list-disc ml-5 mt-1">
                  <li>Home and workspace navigation</li>
                  <li>Release desk: CPI, Employment Situation, GDP Advance — schedule and publication status</li>
                  <li>Market workspace with saved panel layout{excluded ? " (panels show a notice: dataset not included)" : ": charts, indicators, zoom and pan on simulated bars"}</li>
                  {!excluded && <li>Release-event markers (official metadata) on the simulated event-overlay chart data — illustrative alignment only</li>}
                  <li>Import of your own daily OHLCV .csv/.json file into a chart, in this browser tab only</li>
                  <li>Research view{excluded ? " (not included)" : " (illustrative figures)"}</li>
                  <li>This read-only Settings &amp; About page</li>
                </ul>
              </div>
              <div>
                <b>Planned, not implemented</b>
                <ul className="list-disc ml-5 mt-1 dim">
                  <li>Executable strategy backtesting</li>
                  <li>AI research assistant</li>
                  <li>Live data or automatic refresh</li>
                  <li>Point-in-time macro data from official sources</li>
                  <li>Event studies (measured market reactions)</li>
                  <li>User preferences on this page</li>
                </ul>
              </div>
            </div>
          </Section>

          <Section title="Saved layout" id="layout">
            <p>The Market workspace saves its panel layout and panel settings in this browser, for this local address only. Reset it from
              Market → Reset layout. This page reads and changes nothing.</p>
          </Section>

          <Section title="Sources & licences" id="sources">
            <p>Release-desk data: Source: U.S. Bureau of Labor Statistics · Source: U.S. Bureau of Economic Analysis. Not affiliated with or
              endorsed by BLS or BEA.</p>
            <SoftwareLicences />
          </Section>
        </div>
      </main>
    </div>
  );
}
