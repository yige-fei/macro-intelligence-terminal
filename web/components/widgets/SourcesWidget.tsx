"use client";

// New widget: provenance of every displayed number, licence notices and data-rights limits.

import { useQuery } from "@tanstack/react-query";
import { HISTORICAL_DATA, isNotIncluded, loadLocal, type Manifest } from "../../lib/api";
import NotIncluded from "../NotIncluded";

// T4-P1: the software licence notice is shown whether or not the historical snapshot is included.
