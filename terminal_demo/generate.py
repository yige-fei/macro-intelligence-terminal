"""Deterministic generator for the demo data in demo-data/ (Python standard library only).

    python3 -m terminal_demo.generate            # (re)write demo-data/
    python3 -m terminal_demo.generate --check    # exit 1 unless demo-data/ equals a fresh generation

Nothing here reads any dataset. Every value comes from random.Random(SEED) and the fixed parameters below, so the
same seed and generator version always produce byte-identical files.

Market bars (etf_prices.json), four fictional instruments DEMO-A..DEMO-D:
 - calendar: every Monday-Friday from 2016-01-04 to 2023-12-29 (no exchange holidays);
 - each instrument follows a geometric random walk with its own drift and volatility, and a two-state volatility
   regime (calm / stressed) that switches with fixed daily probabilities;
 - a bar opens at the previous close times a small overnight gap, closes at open times the day's return, and its
   high/low extend beyond max/min(open, close) by half-normal amounts; prices are rounded to cents afterwards and
   high/low re-checked so that low <= open, close <= high always holds;
 - volume is a per-instrument base level times a log-normal factor that rises with the absolute daily return;
 - adjClose equals close (there are no dividends in the simulation).
These are well-formed demonstration bars, not a model of real market microstructure.

Research figures (research.json) are ILLUSTRATIVE: each AUC is 0.5 plus a uniform draw in [-0.03, 0.03], the
"macro" AUC adds a further uniform draw in [-0.02, 0.02], the headline estimate is the mean difference and its
interval is the estimate +/- a uniform half-width in [0.01, 0.03]. No model is fitted and nothing is evaluated.
They are not the author's private C5c evaluation and carry none of its identifiers.
"""

import argparse
import hashlib
import json
import math
import random
import sys
from datetime import date, timedelta
from pathlib import Path

from .validate import utc_midnight, validate_etf, validate_manifest, validate_research

GENERATOR = "terminal_demo.generate v1"
SEED = 20261020
START, END = date(2016, 1, 4), date(2023, 12, 29)
REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "demo-data"

# symbol: (start price, annual drift, annual volatility, base volume, description)
INSTRUMENTS = {
    "DEMO-A": (100.0, 0.07, 0.16, 60_000_000, "simulated broad index-like instrument"),
    "DEMO-B": (80.0, 0.10, 0.24, 40_000_000, "simulated higher-volatility growth-like instrument"),
    "DEMO-C": (150.0, 0.05, 0.14, 4_000_000, "simulated lower-volatility instrument"),
    "DEMO-D": (60.0, 0.04, 0.28, 25_000_000, "simulated small-cap-like instrument"),
}
REGIME_VOL = {"calm": 0.8, "stressed": 2.2}         # multiplier on the instrument's volatility
REGIME_SWITCH = {"calm": 0.01, "stressed": 0.05}    # daily probability of leaving the regime


def weekdays(start: date, end: date):
    d = start
    while d <= end:
        if d.weekday() < 5:
            yield d
        d += timedelta(days=1)


def _bars(rng: random.Random, price: float, drift: float, vol: float, base_volume: int, days: list) -> list:
    out, regime, close = [], "calm", price
    dt = 1 / 252
    for d in days:
        if rng.random() < REGIME_SWITCH[regime]:
            regime = "stressed" if regime == "calm" else "calm"
        sigma = vol * REGIME_VOL[regime] * math.sqrt(dt)
        gap = rng.gauss(0, sigma * 0.3)
        ret = rng.gauss((drift - 0.5 * vol * vol) * dt, sigma)
        o = close * math.exp(gap)
        c = o * math.exp(ret)
        h = max(o, c) * math.exp(abs(rng.gauss(0, sigma * 0.5)))
        lo = min(o, c) * math.exp(-abs(rng.gauss(0, sigma * 0.5)))
        o, c, h, lo = (round(x, 2) for x in (o, c, h, lo))
        h, lo = max(h, o, c), max(0.01, min(lo, o, c))
        volume = int(base_volume * math.exp(rng.gauss(0, 0.25)) * (1 + 25 * abs(ret)))
        out.append({"date": d.isoformat(), "time": utc_midnight(d), "open": o, "high": h, "low": lo, "close": c,
                    "adjClose": c, "volume": volume})
        close = c
    return out


def build(seed: int = SEED) -> dict:
    """The demo files as bytes, keyed by file name (ALLOWLIST.json included)."""
    rng = random.Random(seed)
    days = list(weekdays(START, END))
    gen = {"name": GENERATOR, "seed": seed, "calendar": "Monday-Friday, no holidays", "start": START.isoformat(), "end": END.isoformat()}
    etf = {
        "synthetic": True,
        "notice": "SIMULATED DATA - NOT REAL MARKET PRICES. Generated by terminal_demo.generate; no market data was used.",
        "generator": gen,
        "bound": END.isoformat(),
        "source": f"SIMULATED ({GENERATOR}, seed {seed})",
        "symbols": list(INSTRUMENTS),
        "names": {s: p[4] for s, p in INSTRUMENTS.items()},
        "candles": {s: _bars(rng, p[0], p[1], p[2], p[3], days) for s, p in INSTRUMENTS.items()},
    }

    def horizon(label: str) -> dict:
        algos = {}
        for name in ("Model A", "Model B", "Model C"):
            m = round(0.5 + rng.uniform(-0.03, 0.03), 4)
            x = round(m + rng.uniform(-0.02, 0.02), 4)
            algos[name] = {"auc_market_only": m, "auc_macro_enhanced": x, "delta_auc": round(x - m, 4)}
        est = round(sum(a["delta_auc"] for a in algos.values()) / len(algos), 4)
        half = round(rng.uniform(0.01, 0.03), 4)
        return {"label": label, "estimate": est, "interval": [round(est - half, 4), round(est + half, 4)], "ci_level": 0.95,
                "cells_eligible": 24, "cells_total": 24, "invalid_replicates": 0, "replicates": 1000,
                "per_algorithm": algos, "mean_delta_by_year": {f"demo-year-{i}": round(rng.uniform(-0.02, 0.02), 4) for i in range(1, 9)}}

    research = {
        "synthetic": True,
        "illustrative": True,
        "notice": "ILLUSTRATIVE FIGURES - randomly generated by terminal_demo.generate. Not research results; no model was evaluated.",
        "generator": gen,
        "policy_id": "DEMO_ILLUSTRATIVE_v1",
        "policy_sha256": "not applicable (illustrative)",
        "approval_status": "illustrative, not an evaluation",
        "evaluation_sha256": "not applicable (illustrative)",
        "run": "none",
        "label_policy": "none",
        "code_commit": "not applicable",
        "multiplicity": "No multiplicity correction: nothing was tested",
        "review": {"verdict": "not reviewed (illustrative)", "file": "none", "sha256": "not applicable"},
        "results": {"illustrative_1d": horizon("ILLUSTRATIVE"), "illustrative_5d": horizon("ILLUSTRATIVE")},
    }

    enc = lambda o, compact=False: (json.dumps(o, separators=(",", ":")) if compact else json.dumps(o, indent=1)).encode() + b"\n"
    files = {"etf_prices.json": enc(etf, compact=True), "research.json": enc(research)}
    sha = {k: hashlib.sha256(v).hexdigest() for k, v in files.items()}
    manifest = {
        "synthetic": True,
        "notice": "Provenance of the simulated demo data. No third-party data is included.",
        "generator": gen,
        "built_utc": "not time-stamped (deterministic output)",
        "bound": END.isoformat(),
        "snapshot_id": f"synthetic demo data, {GENERATOR}, seed {seed}",
        "snapshot_end": END.isoformat(),
        "repository_head": "not applicable",
        "raw_sha256": {},
        "evidence_sha256": {},
        "files_sha256": sha,
    }
    files["manifest.json"] = enc(manifest)
    validate_etf(etf), validate_research(research), validate_manifest(manifest)
    allow = {"allowlist": "macro-intelligence-terminal demo data", "version": 1,
             "files": {k: hashlib.sha256(v).hexdigest() for k, v in files.items()}}
    files["ALLOWLIST.json"] = enc(allow)
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=OUT_DIR, help="output directory (default: demo-data/ in this repository)")
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on any difference")
    a = ap.parse_args(argv)
    files = build(a.seed)
    if a.check:
        diff = [n for n, b in files.items() if not (a.out / n).is_file() or (a.out / n).read_bytes() != b]
        print("demo data matches the generator" if not diff else "differs from the generator: " + ", ".join(diff))
        return 1 if diff else 0
    a.out.mkdir(parents=True, exist_ok=True)
    for n, b in files.items():
        (a.out / n).write_bytes(b)
    print(f"wrote {len(files)} files to {a.out.name}/ (seed {a.seed})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
